def chegada(codigo, continente, lon, lat):
    """Quando os sapiens chegaram a este ponto (Ma)."""
    for codigos, caixa, idade in CHEGADA:
        if codigos and codigo not in codigos:
            continue
        if caixa and not (caixa[0] <= lon <= caixa[1] and caixa[2] <= lat <= caixa[3]):
            continue
        return idade
    if continente == "Africa":
        return 0.3
    if continente == "Antarctica":
        return A(1900)
    return 0.045


